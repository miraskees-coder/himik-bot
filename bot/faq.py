# Gemini қолжетімсіз болғанда ғана қолданылады: ұзын сұрақтарға FAQ жауабы сай келмейді.
MAX_WORDS_FOR_MATCH = 7


def _contains(text: str, keyword: str) -> bool:
    # Сөз басынан ғана іздейміз: "молекулалар" → "молекула" сәйкес келеді.
    # Қысқа кілт сөздер (ph, рн) толық сөз болуы керек: "phosphorus" → "ph" емес.
    pattern = r"(?<!\w)" + re.escape(keyword)
    if len(keyword) <= 3:
        pattern += r"(?!\w)"
    return re.search(pattern, text) is not None


def match(text: str):
    """Мәтінге ең сәйкес FAQ жазбасын қайтарады, табылмаса None."""
    text = text.lower().strip()
    if not text or len(text.split()) > MAX_WORDS_FOR_MATCH:
        return None

    best, best_score = None, 0
    for item in FAQ:
        score = sum(len(kw) for kw in item["keywords"] if _contains(text, kw))
        if score > best_score:
            best, best_score = item, score
    return best


def faq_knowledge() -> str:
    """Gemini-ге анықтамалық материал ретінде берілетін FAQ (HTML-сыз)."""
    def plain(html: str) -> str:
        return re.sub(r"<[^>]+>", "", html).replace("&lt;", "<").replace("&gt;", ">")

    return "\n\n".join(f"### {item['question']}\n{plain(item['answer'])}" for item in FAQ)
